// Package dialect describes the SQL dialects of the databases that Juju
// supports. It has no dependencies, so that both the database schema
// machinery and the database test suites can share it.
package dialect

// Dialect describes the SQL that differs between database backends when
// managing the schema bookkeeping table.
type Dialect interface {
	// String returns the name of the dialect.
	String() string

	// SchemaTableDDL returns the DDL that creates the schema bookkeeping
	// table, if it does not already exist.
	SchemaTableDDL() string

	// InsertSchemaVersionSQL returns the statement that records an applied
	// schema version. It takes the version and the hash as arguments.
	InsertSchemaVersionSQL() string
}

var (
	// SQLite is the dialect of dqlite and SQLite databases.
	SQLite Dialect = sqlite{}

	// PostgreSQL is the dialect of PostgreSQL databases.
	PostgreSQL Dialect = postgresql{}
)

type sqlite struct{}

// String returns the name of the dialect.
func (sqlite) String() string {
	return "sqlite"
}

// SchemaTableDDL returns the DDL that creates the schema bookkeeping table.
func (sqlite) SchemaTableDDL() string {
	return `
CREATE TABLE IF NOT EXISTS schema (
    id           INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
    version      INTEGER NOT NULL,
    hash         TEXT NOT NULL,
    updated_at   DATETIME NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_schema_version ON schema (version);
`
}

// InsertSchemaVersionSQL returns the statement that records an applied
// schema version.
func (sqlite) InsertSchemaVersionSQL() string {
	return `INSERT INTO schema (version, hash, updated_at) VALUES (?, ?, strftime("%s"));`
}

type postgresql struct{}

// String returns the name of the dialect.
func (postgresql) String() string {
	return "postgresql"
}

// SchemaTableDDL returns the DDL that creates the schema bookkeeping table.
func (postgresql) SchemaTableDDL() string {
	return `
CREATE TABLE IF NOT EXISTS schema (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      BIGINT NOT NULL,
    hash         TEXT NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_schema_version ON schema (version);
`
}

// InsertSchemaVersionSQL returns the statement that records an applied
// schema version.
func (postgresql) InsertSchemaVersionSQL() string {
	return `INSERT INTO schema (version, hash, updated_at) VALUES ($1, $2, now());`
}

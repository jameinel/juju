package dialect

// Dialect identifies SQL syntax independently of the selected database driver.
type Dialect uint8

const (
	// SQLite is shared by SQLite and dqlite.
	SQLite Dialect = iota
	// PostgreSQL is used by the PostgreSQL regression harness.
	PostgreSQL
)

// SchemaTableDDL creates the schema version/hash bookkeeping table.
func (d Dialect) SchemaTableDDL() string {
	switch d {
	case SQLite:
		return `
CREATE TABLE IF NOT EXISTS schema (
    id           INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL,
    version      INTEGER NOT NULL,
    hash         TEXT NOT NULL,
    updated_at   DATETIME NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_schema_version ON schema (version);
`
	case PostgreSQL:
		return `
CREATE TABLE IF NOT EXISTS schema (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version      BIGINT NOT NULL,
    hash         TEXT NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_schema_version ON schema (version);
`
	default:
		panic("unknown database schema dialect")
	}
}

// InsertSchemaVersionSQL records an applied patch's version and hash.
func (d Dialect) InsertSchemaVersionSQL() string {
	switch d {
	case SQLite:
		return `INSERT INTO schema (version, hash, updated_at) VALUES (?, ?, strftime('%s'));`
	case PostgreSQL:
		return `INSERT INTO schema (version, hash, updated_at) VALUES ($1, $2, CURRENT_TIMESTAMP);`
	default:
		panic("unknown database schema dialect")
	}
}

// BeginSchemaChangeSQL serialises schema application within a database.
// It must execute before the transaction's first query.
func (d Dialect) BeginSchemaChangeSQL() string {
	switch d {
	case SQLite:
		return ""
	case PostgreSQL:
		// READ COMMITTED observes DDL committed while waiting for the lock,
		// without retaining long-lived serializable predicate locks.
		// The lock key is the bytes of "juju_ddl" as a big-endian integer.
		return `
SET TRANSACTION ISOLATION LEVEL READ COMMITTED;
SELECT pg_advisory_xact_lock(7671154592639640684);
`
	default:
		panic("unknown database schema dialect")
	}
}

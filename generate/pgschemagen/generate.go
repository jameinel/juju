package main

import (
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

const (
	generatedHeader = "-- Code generated by pgschemagen from the dqlite schema. DO NOT EDIT.\n" +
		"-- To change this file, edit the dqlite schema or add an override; see\n" +
		"-- domain/schema/AGENTS.md.\n\n"

	autoSuffix = "-auto.sql"
	diffSuffix = ".diff"
)

// namespace is one schema namespace (controller or model) to generate.
type namespace struct {
	name string
	// patches are the dqlite patch statements, in order.
	patches []string
	// sqlFiles are the dqlite SQL patch file names, which provide the
	// names of the leading patches.
	sqlFiles []string
}

// output is the generated content of a namespace, keyed by path relative
// to the namespace directory.
type output map[string]string

// generate translates a namespace to PostgreSQL. overrides holds the
// contents of the namespace's override diffs, keyed by file name.
func generate(ns namespace, overrides map[string]string) (output, error) {
	names, err := patchNames(ns)
	if err != nil {
		return nil, err
	}

	tr := newTranslator()
	translated := make([]string, len(ns.patches))
	for i, src := range ns.patches {
		if translated[i], err = tr.translatePatch(src); err != nil {
			return nil, fmt.Errorf("%s patch %s: %w", ns.name, names[i], err)
		}
		if translated[i], err = normaliseSQL(translated[i]); err != nil {
			return nil, fmt.Errorf("%s patch %s: %w", ns.name, names[i], err)
		}
	}

	out := make(output)
	byName := make(map[string]int, len(names))
	for i, n := range names {
		byName[n] = i
	}
	for file, diff := range overrides {
		name, ok := strings.CutSuffix(file, diffSuffix)
		if !ok {
			return nil, fmt.Errorf("%s override %s: not a %s file", ns.name, file, diffSuffix)
		}
		i, ok := byName[name]
		if !ok {
			return nil, fmt.Errorf("%s override %s: no patch named %s", ns.name, file, name)
		}
		out[filepath.Join("overrides", name+autoSuffix)] = translated[i]
		if translated[i], err = applyDiff(translated[i], diff); err != nil {
			return nil, fmt.Errorf("%s override %s: %w", ns.name, file, err)
		}
	}

	ordered, err := orderPatches(translated)
	if err != nil {
		return nil, fmt.Errorf("%s: ordering: %w", ns.name, err)
	}
	for i, text := range ordered {
		text, err := normaliseSQL(text)
		if err != nil {
			return nil, fmt.Errorf("%s patch %s: %w", ns.name, names[i], err)
		}
		out[filepath.Join("sql", names[i]+".sql")] = generatedHeader + strings.TrimLeft(text, "\n")
	}
	return out, nil
}

// normaliseSQL removes trailing layout whitespace, without changing literals
// or function bodies. Function bodies are formatted during translation.
func normaliseSQL(src string) (string, error) {
	toks, err := lex(src)
	if err != nil {
		return "", err
	}
	for i := range toks {
		switch t := &toks[i]; {
		case t.kind == tokComment && strings.HasPrefix(t.text, "--"):
			t.text = strings.TrimRight(t.text, " \t\r")
		case t.kind == tokSpace:
			lines := strings.Split(t.text, "\n")
			for j := range lines[:len(lines)-1] {
				lines[j] = strings.TrimRight(lines[j], " \t\r")
			}
			t.text = strings.Join(lines, "\n")
			if i == len(toks)-1 {
				t.text = strings.TrimRight(t.text, " \t\r\n")
				if len(lines) > 1 {
					t.text += "\n"
				}
			}
		}
	}
	return render(toks), nil
}

// patchNames names each patch NNNN-<slug>, where NNNN is its 0-based index.
// SQL file patches come first and keep their file's slug; the Go-built
// trigger patches that follow are named after the table they watch.
func patchNames(ns namespace) ([]string, error) {
	if len(ns.sqlFiles) > len(ns.patches) {
		return nil, fmt.Errorf("%s: %d SQL files but only %d patches", ns.name, len(ns.sqlFiles), len(ns.patches))
	}
	names := make([]string, len(ns.patches))
	seen := make(map[string]bool)
	for i := range ns.patches {
		var slug string
		if i < len(ns.sqlFiles) {
			stem := strings.TrimSuffix(ns.sqlFiles[i], ".sql")
			_, slug, _ = strings.Cut(stem, "-")
		} else {
			table, err := triggerTable(ns.patches[i])
			if err != nil {
				return nil, fmt.Errorf("%s patch %d: %w", ns.name, i, err)
			}
			slug = "triggers-" + table
		}
		names[i] = fmt.Sprintf("%04d-%s", i, slug)
		if seen[names[i]] {
			return nil, fmt.Errorf("%s: duplicate patch name %s", ns.name, names[i])
		}
		seen[names[i]] = true
	}
	return names, nil
}

// triggerTable returns the table the first trigger of a patch is on.
func triggerTable(src string) (string, error) {
	toks, err := lex(src)
	if err != nil {
		return "", err
	}
	for _, stmt := range splitStatements(toks, true) {
		if !stmt.isCreate("TRIGGER") {
			continue
		}
		trg, err := parseTrigger(stmt.body)
		if err != nil {
			return "", err
		}
		return strings.ReplaceAll(trg.table[0].name(), "_", "-"), nil
	}
	return "", fmt.Errorf("Go-built patch contains no trigger")
}

// readOverrides reads the override diffs in dir, which may not exist.
func readOverrides(dir string) (map[string]string, error) {
	entries, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return nil, nil
	} else if err != nil {
		return nil, err
	}
	overrides := make(map[string]string)
	for _, e := range entries {
		name := e.Name()
		switch {
		case e.IsDir(), strings.HasSuffix(name, autoSuffix):
		case strings.HasSuffix(name, diffSuffix):
			data, err := os.ReadFile(filepath.Join(dir, name))
			if err != nil {
				return nil, err
			}
			overrides[name] = string(data)
		default:
			return nil, fmt.Errorf("unexpected file %s", filepath.Join(dir, name))
		}
	}
	return overrides, nil
}

// readSQLFiles lists the dqlite SQL patch files of a namespace. Post-patch
// files are not supported for PostgreSQL yet, so finding one is an error.
func readSQLFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var files []string
	for _, e := range entries {
		name := e.Name()
		switch {
		case e.IsDir(), !strings.HasSuffix(name, ".sql"):
		case strings.HasSuffix(name, ".PATCH.sql"):
			return nil, fmt.Errorf("post-patch %s is not supported for PostgreSQL", filepath.Join(dir, name))
		default:
			files = append(files, name)
		}
	}
	slices.Sort(files)
	return files, nil
}

// writeOutput writes the generated files of a namespace to dir, and removes
// generated files that are no longer produced.
func writeOutput(dir string, out output) error {
	for _, sub := range []string{"sql", "overrides"} {
		entries, err := os.ReadDir(filepath.Join(dir, sub))
		if os.IsNotExist(err) {
			continue
		} else if err != nil {
			return err
		}
		for _, e := range entries {
			rel := filepath.Join(sub, e.Name())
			generated := sub == "sql" || strings.HasSuffix(e.Name(), autoSuffix)
			if _, ok := out[rel]; generated && !ok {
				if err := os.Remove(filepath.Join(dir, rel)); err != nil {
					return err
				}
			}
		}
	}
	for rel, text := range out {
		path := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
			return err
		}
	}
	return nil
}

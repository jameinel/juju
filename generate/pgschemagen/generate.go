package main

import (
	"crypto/sha256"
	"fmt"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"

	coreschema "github.com/juju/juju/core/database/schema"
	"github.com/juju/juju/core/version"
	"github.com/juju/juju/domain/schema"
)

const generatedHeader = "-- Code generated by pgschemagen. DO NOT EDIT.\n"

type namespace struct {
	name           string
	sources        []schema.PatchSource
	postPatchFiles []string
}

type output map[string]string

// run generates and preflights every namespace before writing any of them.
// Translation failures must not leave a plausible partial controller schema.
func run(namespaces []namespace, sourceDir, destDir string, check bool) error {
	if len(namespaces) != 2 {
		return fmt.Errorf("both controller and model namespaces are required")
	}
	out := make(output)
	seen := make(map[string]bool)
	for _, ns := range namespaces {
		if ns.name != "controller" && ns.name != "model" || seen[ns.name] {
			return fmt.Errorf("invalid or duplicate namespace %q", ns.name)
		}
		seen[ns.name] = true
		if err := validateSources(ns, sourceDir); err != nil {
			return fmt.Errorf("%s inputs: %w", ns.name, err)
		}
		overrides, err := readOverrides(filepath.Join(destDir, ns.name, "overrides"))
		if err != nil {
			return fmt.Errorf("%s overrides: %w", ns.name, err)
		}
		files, err := generate(ns, overrides)
		if err != nil {
			return err
		}
		for name, text := range files {
			out[path.Join(ns.name, name)] = text
		}
	}
	return syncOutput(destDir, out, check)
}

func validateSources(ns namespace, sourceDir string) error {
	prefix := path.Join("dqlite", ns.name, "sql") + "/"
	expected := make(map[string]string)
	registered := make(map[string]bool)
	for _, name := range ns.postPatchFiles {
		if !strings.HasPrefix(name, prefix) || !strings.HasSuffix(name, ".PATCH.sql") ||
			path.Dir(name)+"/" != prefix || registered[name] {
			return fmt.Errorf("invalid or duplicate registered post-patch %q", name)
		}
		registered[name] = true
	}
	seen := make(map[string]bool)
	if len(ns.sources) == 0 {
		return fmt.Errorf("schema has no patch sources")
	}
	for i, source := range ns.sources {
		if seen[source.Name] {
			return fmt.Errorf("duplicate source %q", source.Name)
		}
		seen[source.Name] = true
		if coreschema.HasArgs(source.Patch) {
			return fmt.Errorf("source %q has bound arguments; SQL-only generation is unsupported", source.Name)
		}
		if !strings.HasSuffix(source.Name, ".sql") {
			if source.Name != fmt.Sprintf("%s.go#patch-%04d", ns.name, i) {
				return fmt.Errorf("unexpected Go source identity %q", source.Name)
			}
			continue
		}
		if !strings.HasPrefix(source.Name, prefix) || path.Dir(source.Name)+"/" != prefix {
			return fmt.Errorf("unexpected SQL source %q", source.Name)
		}
		if strings.HasSuffix(source.Name, ".PATCH.sql") && !registered[source.Name] {
			return fmt.Errorf("unregistered post-patch %q", source.Name)
		}
		expected[source.Name] = coreschema.Stmt(source.Patch)
	}
	dir := filepath.Join(sourceDir, ns.name, "sql")
	if err := rejectSymlinkDirs(dir); err != nil {
		return err
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		name := prefix + entry.Name()
		if !entry.Type().IsRegular() {
			return fmt.Errorf("unexpected non-regular input %q", name)
		}
		want, selected := expected[name]
		if !selected {
			if registered[name] {
				continue
			}
			return fmt.Errorf("unexpected or unregistered input %q", name)
		}
		data, err := os.ReadFile(filepath.Join(dir, entry.Name()))
		if err != nil {
			return err
		}
		if string(data) != want {
			return fmt.Errorf("source %q differs from compiled schema; rerun go run to rebuild the generator", name)
		}
		delete(expected, name)
	}
	if names := sortedKeys(expected); len(names) != 0 {
		return fmt.Errorf("missing selected source %q", names[0])
	}
	return nil
}

func generate(ns namespace, overrides map[string]string) (output, error) {
	tr := newTranslator()
	out := make(output)
	unused := make(map[string]bool)
	for name := range overrides {
		unused[name] = true
	}
	for i, source := range ns.sources {
		if coreschema.HasArgs(source.Patch) {
			return nil, fmt.Errorf("%s source %s: bound arguments are unsupported", ns.name, source.Name)
		}
		src := coreschema.Stmt(source.Patch)
		text, err := tr.translatePatch(src)
		if err != nil {
			return nil, fmt.Errorf("%s source %s: %w", ns.name, source.Name, err)
		}
		stem := fmt.Sprintf("%04d-%s", i, strings.ReplaceAll(strings.TrimSuffix(path.Base(source.Name), ".sql"), "#", "-"))
		diffName := stem + ".diff"
		header := fmt.Sprintf("%s-- Source: %s\n-- Source SHA-256: %x\n-- Juju version: %s\n\n",
			generatedHeader, source.Name, sha256.Sum256([]byte(src)), version.Current)
		if diff, ok := overrides[diffName]; ok {
			delete(unused, diffName)
			body, err := overrideBody(source.Name, diff)
			if err != nil {
				return nil, fmt.Errorf("%s override %s: %w", ns.name, diffName, err)
			}
			// Until dependency analysis can reparse arbitrary overridden SQL,
			// overrides may change literals/comments, not the schema structure.
			raw := header + text
			changed, err := applyDiff(text, body)
			if err != nil {
				return nil, fmt.Errorf("%s override %s: %w", ns.name, diffName, err)
			}
			if err := validateOverrideStructure(text, changed); err != nil {
				return nil, fmt.Errorf("%s override %s: %w", ns.name, diffName, err)
			}
			out[path.Join("overrides", stem+"-auto.sql")] = raw
			text = changed
		}
		out[path.Join("sql", stem+".sql")] = header + text
	}
	if names := sortedKeys(unused); len(names) != 0 {
		return nil, fmt.Errorf("%s unused override %s", ns.name, names[0])
	}
	return out, nil
}

func overrideBody(source, diff string) (string, error) {
	for _, key := range []string{"Source", "Reason", "Remove-when"} {
		line, rest, ok := strings.Cut(diff, "\n")
		value, found := strings.CutPrefix(line, "# "+key+": ")
		if !ok || !found || strings.TrimSpace(value) == "" {
			return "", fmt.Errorf("missing %s provenance header", key)
		}
		if key == "Source" && value != source {
			return "", fmt.Errorf("override source %q does not match %q", value, source)
		}
		diff = rest
	}
	return diff, nil
}

func validateOverrideStructure(before, after string) error {
	var structure [2][]token
	for i, src := range []string{before, after} {
		toks, err := lex(src)
		if err != nil {
			return err
		}
		if _, err := splitStatements(toks, false); err != nil {
			return err
		}
		for _, tok := range toks {
			if tok.isTrivia() {
				continue
			}
			if tok.kind == tokNumber || tok.kind == tokString {
				tok.text = ""
			}
			structure[i] = append(structure[i], tok)
		}
	}
	if !slices.Equal(structure[0], structure[1]) {
		return fmt.Errorf("structural overrides require dependency validation, not yet implemented")
	}
	return nil
}

func readOverrides(dir string) (map[string]string, error) {
	if err := rejectSymlinkDirs(dir); err != nil {
		return nil, err
	}
	entries, err := os.ReadDir(dir)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	out := make(map[string]string)
	for _, entry := range entries {
		name := entry.Name()
		if !entry.Type().IsRegular() {
			return nil, fmt.Errorf("unexpected non-regular override %q", name)
		}
		if strings.HasSuffix(name, "-auto.sql") {
			continue
		}
		if !strings.HasSuffix(name, ".diff") {
			return nil, fmt.Errorf("unexpected override file %q", name)
		}
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			return nil, err
		}
		out[name] = string(data)
	}
	return out, nil
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	return keys
}

func (s *generatorSuite) TestLongIdentifiers(c *tc.C) {
	a := strings.Repeat("a", 70)
	b := a + "b"
	c.Check(len(shortIdent(a)), tc.Equals, 63)
	c.Check(shortIdent(a), tc.Equals, shortIdent(a))
	c.Check(shortIdent(a) == shortIdent(b), tc.IsFalse)
	c.Check(shortIdent("short"), tc.Equals, "short")
	got, err := newTranslator().translatePatch("CREATE INDEX " + a + " ON t (id);")
	c.Assert(err, tc.ErrorIsNil)
	c.Check(got, tc.Equals, "CREATE INDEX "+shortIdent(a)+" ON t (id);")
}

func (s *generatorSuite) TestTriggers(c *tc.C) {
	for _, test := range []struct {
		src  string
		want []string
	}{
		{`CREATE TRIGGER trg BEFORE UPDATE OF n ON t FOR EACH ROW
WHEN NEW.n < OLD.n BEGIN SELECT RAISE(ABORT, 'backwards'); END;`,
			[]string{"BEFORE UPDATE OF n ON t", "IF NEW.n < OLD.n THEN",
				"RAISE EXCEPTION USING MESSAGE = 'backwards';", "RETURN NEW;"}},
		{`CREATE TRIGGER trg BEFORE DELETE ON t BEGIN SELECT RAISE(FAIL, 'no') WHERE OLD.n = 1; END;`,
			[]string{"IF OLD.n = 1 THEN", "RETURN OLD;"}},
		{`CREATE TRIGGER trg AFTER INSERT ON t BEGIN SELECT RAISE(FAIL, 'no') FROM t WHERE n = NEW.n; END;`,
			[]string{"IF EXISTS (SELECT 1 FROM t WHERE n = NEW.n) THEN", "RETURN NULL;"}},
		{`CREATE TRIGGER trg AFTER INSERT ON t BEGIN SELECT IFNULL(NEW.n, 0); INSERT INTO log VALUES (NEW.n); END;`,
			[]string{"PERFORM COALESCE(NEW.n, 0);", "INSERT INTO log VALUES (NEW.n);", "RETURN NULL;"}},
	} {
		got, err := newTranslator().translatePatch(test.src)
		c.Assert(err, tc.ErrorIsNil)
		for _, want := range test.want {
			c.Check(strings.Contains(got, want), tc.IsTrue, tc.Commentf("%s", got))
		}
		c.Check(strings.Contains(got, "CREATE FUNCTION trg() RETURNS trigger"), tc.IsTrue)
		c.Check(strings.Contains(got, "FOR EACH ROW EXECUTE FUNCTION trg();"), tc.IsTrue)
	}
	for _, src := range []string{
		"CREATE TRIGGER t", "CREATE TRIGGER t AFTER INSERT ON",
		"CREATE TRIGGER t INSTEAD OF INSERT ON v BEGIN SELECT 1; END;",
		"CREATE TRIGGER t BEFORE INSERT ON v BEGIN SELECT RAISE(ROLLBACK, 'no'); END;",
	} {
		_, err := newTranslator().translatePatch(src)
		c.Check(err, tc.NotNil)
	}
	got, err := newTranslator().translatePatch("CREATE TABLE change_log (id INTEGER PRIMARY KEY AUTOINCREMENT);")
	c.Assert(err, tc.ErrorIsNil)
	c.Check(strings.HasPrefix(got, "CREATE TABLE change_log (id BIGINT PRIMARY KEY);"), tc.IsTrue,
		tc.Commentf("change_log.id must not be an identity column:\n%s", got))
	c.Check(strings.Contains(got, changeLogLock), tc.IsTrue)
	c.Check(strings.Index(changeLogLock, "pg_advisory_xact_lock") < strings.Index(changeLogLock, "NEW.id := nextval"),
		tc.IsTrue)
	c.Check(strings.Contains(changeLogLock, "CREATE SEQUENCE change_log_id_seq OWNED BY change_log.id;"), tc.IsTrue)
	c.Check(strings.Contains(changeLogLock, "IF NEW.id IS NULL THEN"), tc.IsTrue)
}

func (s *generatorSuite) TestOrdering(c *tc.C) {
	for _, test := range []struct {
		name    string
		patches []string
		moved   []string
	}{
		{"forward FK", []string{
			"CREATE TABLE a (id BIGINT PRIMARY KEY, b BIGINT, FOREIGN KEY (b) REFERENCES b (id));",
			"CREATE TABLE b (id BIGINT PRIMARY KEY); INSERT INTO b VALUES (1);",
		}, []string{`ALTER TABLE "a" ADD FOREIGN KEY (b) REFERENCES b (id);`}},
		{"unique index", []string{
			"CREATE TABLE b (id BIGINT); CREATE TABLE a (b BIGINT, FOREIGN KEY (b) REFERENCES b (id));",
			"CREATE UNIQUE INDEX idx_b ON b (id);",
		}, []string{`ALTER TABLE "a" ADD FOREIGN KEY (b) REFERENCES b (id);`}},
		{"cycle", []string{
			"CREATE TABLE a (id BIGINT PRIMARY KEY, b BIGINT, FOREIGN KEY (b) REFERENCES b (id));",
			"CREATE TABLE b (id BIGINT PRIMARY KEY, a BIGINT, FOREIGN KEY (a) REFERENCES a (id));",
		}, []string{`ALTER TABLE "a" ADD FOREIGN KEY (b) REFERENCES b (id);`,
			`ALTER TABLE "b" ADD FOREIGN KEY (a) REFERENCES a (id);`}},
		{"views", []string{
			"CREATE VIEW v2 AS SELECT * FROM v1; CREATE VIEW v1 AS WITH x AS (SELECT * FROM t) SELECT * FROM x;",
			"CREATE TABLE t (id BIGINT); INSERT INTO t VALUES (1);",
		}, []string{"CREATE VIEW v1", "CREATE VIEW v2"}},
		{"same patch", []string{
			"CREATE VIEW v AS SELECT * FROM t; CREATE TABLE t (id BIGINT); INSERT INTO t VALUES (1);",
		}, []string{"CREATE VIEW v"}},
	} {
		out, err := orderPatches(test.patches)
		c.Assert(err, tc.ErrorIsNil, tc.Commentf("%s", test.name))
		c.Check(len(out), tc.Equals, len(test.patches))
		last := out[len(out)-1]
		previous := -1
		for _, text := range test.moved {
			at := strings.Index(last, text)
			c.Check(at > previous, tc.IsTrue, tc.Commentf("%s: %s", test.name, last))
			previous = at
		}
		if len(out) > 1 {
			c.Check(strings.Contains(out[0], "FOREIGN KEY"), tc.IsFalse)
			c.Check(strings.Contains(out[0], "CREATE VIEW"), tc.IsFalse)
		}
		c.Check(strings.Index(last, "INSERT INTO") < strings.Index(last, "-- Moved"), tc.IsTrue)
	}
}

func (s *generatorSuite) TestOrderingErrors(c *tc.C) {
	for _, test := range []struct{ src, err string }{
		{"CREATE TABLE a (b BIGINT, FOREIGN KEY (b) REFERENCES missing (id));", `.*dangling reference.*`},
		{"CREATE VIEW a AS SELECT * FROM b; CREATE VIEW b AS SELECT * FROM a;", `.*view cycle.*`},
		{"CREATE VIEW a AS SELECT * FROM missing;", `.*dangling reference.*`},
		{"CREATE TABLE a (b BIGINT, FOREIGN KEY (b) REFERENCES b (id)); CREATE TABLE b (id BIGINT);",
			`.*no unique key.*`},
	} {
		_, err := orderPatches([]string{test.src})
		c.Check(err, tc.ErrorMatches, test.err)
	}
}

func (s *generatorSuite) TestDiff(c *tc.C) {
	for _, test := range []struct{ src, diff, want string }{
		{"a\nb\nc\n", "@@ -1,3 +1,3 @@\n a\n-b\n+B\n c\n", "a\nB\nc\n"},
		{"prefix\na\nb\n", "--- a\n+++ b\n@@ -1,2 +1,2 @@\n a\n-b\n+B\n", "prefix\na\nB\n"},
		{"a\n", "@@ -0,0 +1 @@\n+first\n", "first\na\n"},
		{"a\nb\n", "@@ -1,0 +2 @@\n+middle\n", "a\nmiddle\nb\n"},
		{"a\nb\n", "@@ -2 +1,0 @@\n-b\n", "a\n"},
		{"a", "@@ -1 +1 @@\n-a\n\\ No newline at end of file\n+b\n\\ No newline at end of file\n", "b"},
		{"a\nb\nc\n", "@@ -1 +1 @@\n-a\n+A\n@@ -3 +3 @@\n-c\n+C\n", "A\nb\nC\n"},
		{"unchanged", "", "unchanged"},
	} {
		got, err := applyDiff(test.src, test.diff)
		c.Assert(err, tc.ErrorIsNil)
		c.Check(got, tc.Equals, test.want)
	}
	for _, diff := range []string{
		"@@ -1 +1 @@\n-wrong\n+new\n", "@@ invalid @@\n", "not a diff",
		"@@ -1,2 +1 @@\n-a\n+b\n", "@@ --1 +1 @@\n-a\n+b\n",
	} {
		_, err := applyDiff("a\n", diff)
		c.Check(err, tc.NotNil)
	}
}

func (s *generatorSuite) TestOverrides(c *tc.C) {
	ns := namespace{
		name: "test", sqlFiles: []string{"0000-base.sql"},
		patches: []string{"CREATE TABLE t (n INT);"},
	}
	raw := "CREATE TABLE t (n BIGINT);"
	out, err := generate(ns, map[string]string{"0000-base.diff": ""})
	c.Assert(err, tc.ErrorIsNil)
	c.Check(out["overrides/0000-base-auto.sql"], tc.Equals, raw)
	c.Check(out["sql/0000-base.sql"], tc.Equals, generatedHeader+raw)
	_, err = generate(ns, map[string]string{"missing.diff": ""})
	c.Check(err, tc.ErrorMatches, `.*no patch named missing`)
	_, err = generate(ns, map[string]string{"0000-base.diff": "@@ -1 +1 @@\n-no longer matches\n+new\n"})
	c.Check(err, tc.ErrorMatches, `.*does not apply`)

	dir := c.MkDir()
	c.Assert(os.WriteFile(filepath.Join(dir, "0001-base.PATCH.sql"), nil, 0o600), tc.ErrorIsNil)
	_, err = readSQLFiles(dir)
	c.Check(err, tc.ErrorMatches, `.*post-patch.*not supported.*`)
	c.Assert(writeOutput(dir, output{"sql/old.sql": "old", "overrides/old-auto.sql": "old"}), tc.ErrorIsNil)
	c.Assert(os.WriteFile(filepath.Join(dir, "overrides", "keep.diff"), nil, 0o600), tc.ErrorIsNil)
	c.Assert(writeOutput(dir, output{"sql/new.sql": "new"}), tc.ErrorIsNil)
	_, err = os.Stat(filepath.Join(dir, "sql", "old.sql"))
	c.Check(os.IsNotExist(err), tc.IsTrue)
	_, err = os.Stat(filepath.Join(dir, "overrides", "old-auto.sql"))
	c.Check(os.IsNotExist(err), tc.IsTrue)
	_, err = os.Stat(filepath.Join(dir, "overrides", "keep.diff"))
	c.Check(err, tc.ErrorIsNil)
}

func (s *generatorSuite) TestGeneratedFilesAreCurrent(c *tc.C) {
	root, err := filepath.Abs("../../domain/schema")
	c.Assert(err, tc.ErrorIsNil)
	for name, ddl := range map[string]*coreschema.Schema{
		"controller": schema.ControllerDDL(), "model": schema.ModelDDL(),
	} {
		out, err := generateNamespace(name, ddl, filepath.Join(root, "dqlite"), filepath.Join(root, "postgresql"))
		c.Assert(err, tc.ErrorIsNil)
		dir := filepath.Join(root, "postgresql", name)
		for rel, want := range out {
			got, err := os.ReadFile(filepath.Join(dir, rel))
			c.Assert(err, tc.ErrorIsNil)
			c.Check(string(got), tc.Equals, want, tc.Commentf("regenerate %s/%s", name, rel))
		}
		for _, sub := range []string{"sql", "overrides"} {
			entries, err := os.ReadDir(filepath.Join(dir, sub))
			if os.IsNotExist(err) && sub == "overrides" {
				continue
			}
			c.Assert(err, tc.ErrorIsNil)
			for _, entry := range entries {
				if strings.HasSuffix(entry.Name(), diffSuffix) {
					continue
				}
				_, exists := out[filepath.Join(sub, entry.Name())]
				c.Check(exists, tc.IsTrue, tc.Commentf("stale generated file %s/%s/%s", name, sub, entry.Name()))
			}
		}
	}
}

func (s *generatorSuite) TestLexAndSplit(c *tc.C) {
	for _, test := range []struct {
		sql    string
		sqlite bool
		count  int
	}{
		{`-- semicolon ;
CREATE TABLE t (s TEXT DEFAULT 'a;''b', "quoted;name" TEXT);`, true, 1},
		{`CREATE TRIGGER trg AFTER UPDATE ON t BEGIN
SELECT CASE WHEN NEW.n > 1 THEN ';' ELSE 'END' END;
UPDATE t SET n = 1; END; SELECT 2;`, true, 2},
		{`CREATE FUNCTION f() RETURNS trigger LANGUAGE plpgsql AS $tag$
BEGIN PERFORM 1; RETURN NEW; END; $tag$; SELECT 2;`, false, 2},
		{"/* comment */ SELECT `a``b`, 2;\n-- tail", false, 1},
	} {
		toks, err := lex(test.sql)
		c.Assert(err, tc.ErrorIsNil)
		c.Check(render(toks), tc.Equals, test.sql)
		statements := splitStatements(toks, test.sqlite)
		var text strings.Builder
		var count int
		for _, stmt := range statements {
			text.WriteString(stmt.text())
			if len(stmt.body) > 0 {
				count++
			}
		}
		c.Check(text.String(), tc.Equals, test.sql)
		c.Check(count, tc.Equals, test.count)
	}
	for _, src := range []string{"'unterminated", "/* unfinished", "$tag$missing end"} {
		_, err := lex(src)
		c.Check(err, tc.NotNil)
	}
}

func (s *generatorSuite) TestTranslation(c *tc.C) {
	for _, test := range []struct {
		src, want string
	}{
		{"CREATE TABLE user (id INTEGER PRIMARY KEY AUTOINCREMENT, n INT, b BLOB, t DATETIME) STRICT;",
			`CREATE TABLE "user" (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, n BIGINT, b BYTEA, t TIMESTAMPTZ);`},
		{"CREATE TABLE t (id INTEGER PRIMARY KEY, b BOOLEAN DEFAULT 0, CONSTRAINT pk_t PRIMARY KEY (b)) WITHOUT ROWID;",
			"CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, b BOOLEAN DEFAULT FALSE, PRIMARY KEY (b));"},
		{"SELECT IIF(a == 1, IFNULL(b, 2), IIF(c, 3, 4));",
			"SELECT CASE WHEN a = 1 THEN COALESCE(b, 2) ELSE CASE WHEN c THEN 3 ELSE 4 END END;"},
		{"SELECT DATETIME('now', 'utc'), STRFTIME('%Y-%m-%d %H:%M:%f', 'NOW', 'utc');",
			"SELECT now(), now();"},
		{`SELECT 'user DATETIME(''now'')', "constraint", u.user;`,
			`SELECT 'user DATETIME(''now'')', "constraint", u.user;`},
		{"CREATE TABLE t (b BOOLEAN DEFAULT 1); INSERT INTO t VALUES (0), (1);",
			"CREATE TABLE t (b BOOLEAN DEFAULT TRUE); INSERT INTO t VALUES (FALSE), (TRUE);"},
		{"CREATE TABLE t (n INT, b BOOLEAN); INSERT INTO t (b, n) VALUES (1, 0), (0, 1);",
			"CREATE TABLE t (n BIGINT, b BOOLEAN); INSERT INTO t (b, n) VALUES (TRUE, 0), (FALSE, 1);"},
	} {
		got, err := newTranslator().translatePatch(test.src)
		c.Assert(err, tc.ErrorIsNil, tc.Commentf("%s", test.src))
		c.Check(got, tc.Equals, test.want)
	}
	tr := newTranslator()
	_, err := tr.translatePatch("CREATE TABLE t (b BOOLEAN);")
	c.Assert(err, tc.ErrorIsNil)
	got, err := tr.translatePatch("INSERT INTO t VALUES (1);")
	c.Assert(err, tc.ErrorIsNil)
	c.Check(got, tc.Equals, "INSERT INTO t VALUES (TRUE);")
	for _, src := range []string{
		"SELECT GROUP_CONCAT(n);", "SELECT DATETIME('now', '+1 day');",
		"SELECT STRFTIME('%d', 'now');", "CREATE TABLE t (n UNKNOWN);",
	} {
		_, err := newTranslator().translatePatch(src)
		c.Check(err, tc.NotNil, tc.Commentf("%s", src))
	}
}

